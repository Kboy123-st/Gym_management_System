export const initialMemberships: Membership[] = initialMembers.map((mem, i) => {
  const plan = initialPlans[i % initialPlans.length];
  const start = todayISO(-(i * 10));
  const end = todayISO(plan.durationDays - i * 10);
  let status: 'Active' | 'Expired' | 'Frozen' | 'Cancelled' = 'Active';
  if (plan.durationDays - i * 10 < 0) status = 'Expired';
  if (i === 3) status = 'Frozen';
  if (i === 7) status = 'Cancelled';

  return {
    id: `MS-${String(1001 + i).padStart(4, '0')}`,
    memberId: mem.id,
    planId: plan.id,
    startDate: start,
    endDate: end,
    status,
    assignedDate: start,
    autoRenew: plan.isRecurring && status !== 'Cancelled',
    nextBillingDate: status === 'Active' ? end : '',
    recurringAmount: plan.price,
    paymentMethod: i % 2 === 0 ? 'Credit Card' : 'Bank Transfer',
  };
});

